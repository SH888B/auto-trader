def grid(dates, codes):
    cols = [f"{NAMES[c]}{'(BJ30%)' if c.endswith('.BJ') else ''}" for c in codes]
    rows = []
    for d in dates:
        df = load(d)
        row = {}
        for c in codes:
            if c in df.index:
                r = df.loc[c]
                v = float(r["pct_chg"])
                hi, cl = float(r["high"]), float(r["close"])
                op = float(r["open"])
                tag = ""
                if v > 9.8 and c.endswith(".SH") and not c.startswith("68"): tag = "涨停" if abs(hi-cl)/cl < 0.003 else "炸板"
                elif v > 19.8 and (c.startswith("30") or c.startswith("68")): tag = "涨停" if abs(hi-cl)/cl < 0.003 else "炸板"
                elif v < -9.8 and c.endswith(".SH") and not c.startswith("68"): tag = "跌停"
                elif v < -19.8 and (c.startswith("30") or c.startswith("68")): tag = "跌停"
                elif v < -8.5 and c.endswith(".SH") and not c.startswith("68"): tag = "近跌停"
                row[cols[codes.index(c)]] = f"{v:+.1f}{tag}"
            else:
                row[cols[codes.index(c)]] = "-"
        rows.append(pd.Series(row, name=d))
    return pd.DataFrame(rows)

